import { h } from "./dom.js";

export const aiLabel = () => h("span", { class: "ai-label", title: "Generated by AI" }, "AI-generated");

export function notice(kind, ...children) {
  return h("div", { class: `notice ${kind}`, role: kind === "error" ? "alert" : "status" }, children);
}

export function loading(message) {
  return h("div", { class: "loading", role: "status" }, h("span", { class: "spinner", "aria-hidden": "true" }), message);
}

export function skeletonLines(count = 3) {
  return h(
    "div",
    { class: "skeleton", "aria-hidden": "true" },
    Array.from({ length: count }, () => h("span", { class: "skeleton-line" })),
  );
}

export function emptyState(title, hint) {
  return h("div", { class: "empty" }, h("strong", { text: title }), hint ? h("p", { text: hint }) : null);
}

export function card(title, { actions = null, className = "" } = {}, ...body) {
  return h(
    "section",
    { class: `card ${className}`.trim() },
    h("header", { class: "card-head" }, h("h2", { text: title }), actions),
    ...body,
  );
}

/** Calls onTick(secondsLeft) every second, then onDone(). Returns a cancel function. */
export function startCountdown(seconds, onTick, onDone) {
  let left = seconds;
  onTick(left);
  const timer = setInterval(() => {
    left -= 1;
    if (left <= 0) {
      clearInterval(timer);
      onDone();
    } else {
      onTick(left);
    }
  }, 1000);
  return () => clearInterval(timer);
}
